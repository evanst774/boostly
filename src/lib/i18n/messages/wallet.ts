/** "1,500 RWF" / "1 500 RWF" / "RWF 1,500" for the current language. */
export function useRwf() {
  const tc = useT(common);
  const fmt = useFormatNumber();
  return useCallback((n: number) => tc('rwf', { amount: fmt(Math.round(n)) }), [tc, fmt]);
}

/** Localised payout day, countdown and withdrawal frequency. */
export function usePayoutText() {
  const t = useT(wallet);
  const { locale } = useLocale();
  const tag = LOCALE_TAGS[locale];

  const payoutDay = useCallback(
    (payoutAt: Date, now: Date = new Date()) => {
      const time = t('payoutTime');
      const dayDiff = Math.round(
        (Date.parse(kigaliDateKey(payoutAt)) - Date.parse(kigaliDateKey(now))) / 86_400_000,
      );
      if (dayDiff === 0) return t('payoutToday', { time });
      if (dayDiff === 1) return t('payoutTomorrow', { time });
      const date = payoutAt.toLocaleDateString(tag, {
        weekday: 'short',
        day: 'numeric',
        month: 'short',
        timeZone: PAYOUT_TIMEZONE,
      });
      return t('payoutOn', { date, time });
    },
    [t, tag],
  );

  const countdown = useCallback(
    (ms: number) => {
      if (ms <= 0) return t('countdownNow');
      const totalMinutes = Math.ceil(ms / 60000);
      const d = Math.floor(totalMinutes / 1440);
      const h = Math.floor((totalMinutes % 1440) / 60);
      const m = totalMinutes % 60;
      if (d > 0) return t('durDaysHours', { d, h });
      if (h > 0) return t('durHoursMinutes', { h, m });
      return t('durMinutes', { m });
    },
    [t],
  );

  const frequency = useCallback(
    (days: number) => {
      if (days <= 1) return t('freqDaily');
      if (days === 7) return t('freqWeekly');
      return t('freqEvery', { n: days });
    },
    [t],
  );

  return { payoutDay, countdown, frequency, payoutTime: t('payoutTime'), tag };
}

/** The withdrawal "not now" message in the member's language. */
export function useWithdrawReason() {
  const t = useT(wallet);
  const rwf = useRwf();
  const { frequency } = usePayoutText();
  return useCallback(
    (e: { reason: string | null; reasonCode?: string | null; intervalDays: number; minAmount: number; plan: { name: string } }) => {
      if (e.reasonCode === 'ALREADY_TODAY') return t('reasonToday');
      if (e.reasonCode === 'INTERVAL')
        return t('reasonInterval', { plan: e.plan.name.replace(/ Plan$/, ''), frequency: frequency(e.intervalDays).toLowerCase() });
      if (e.reasonCode === 'MIN_BALANCE') return t('reasonMin', { amount: rwf(e.minAmount) });
      return e.reason ?? '';
    },
    [t, rwf, frequency],
  );
}
